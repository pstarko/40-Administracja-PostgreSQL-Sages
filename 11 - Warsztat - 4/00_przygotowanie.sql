    uwagi      text
);

CREATE TABLE pozycje_zamowien (
    id             bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    zamowienie_id  bigint NOT NULL REFERENCES zamowienia(id),
    produkt_id     int    NOT NULL REFERENCES produkty(id),
    ilosc          int    NOT NULL CHECK (ilosc > 0),
    cena           numeric(10,2) NOT NULL
);
CREATE INDEX ON pozycje_zamowien (zamowienie_id);
CREATE INDEX ON pozycje_zamowien (produkt_id);

CREATE TABLE wysylki (
    id             bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    zamowienie_id  bigint NOT NULL,
    status         text NOT NULL DEFAULT 'oczekuje',
    pobrano_przez  text,
    pobrano        timestamptz
);

