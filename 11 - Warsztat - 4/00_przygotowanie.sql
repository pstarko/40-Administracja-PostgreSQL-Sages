-- 4. Logika „aplikacji” ------------------------------------------------
-- Składa zamówienie na jeden produkt – POPRAWNY wzorzec (atomowy UPDATE z warunkiem)
CREATE FUNCTION zloz_zamowienie(p_klient bigint, p_produkt int, p_ilosc int, p_uwagi text)
RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE
    v_cena numeric;
    v_id   bigint;
BEGIN
    UPDATE produkty
       SET stan = stan - p_ilosc
     WHERE id = p_produkt AND stan >= p_ilosc
    RETURNING cena INTO v_cena;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Brak towaru: produkt % (zamówiono % szt.)', p_produkt, p_ilosc;
    END IF;

    INSERT INTO zamowienia (klient_id, status, kwota, uwagi)
    VALUES (p_klient, 'nowe', v_cena * p_ilosc, p_uwagi)
    RETURNING id INTO v_id;

    INSERT INTO pozycje_zamowien (zamowienie_id, produkt_id, ilosc, cena)
    VALUES (v_id, p_produkt, p_ilosc, v_cena);

    RETURN v_id;
END $$;

-- Składa zamówienie z koszyka (wiele produktów).
-- p_pauza_s symuluje „wolną aplikację” (np. wywołanie API między pozycjami).
-- UWAGA: ta wersja ma błąd projektowy, który odkryjemy w module 4.
CREATE FUNCTION zloz_zamowienie_koszyk(p_klient bigint, p_produkty int[], p_ilosci int[],
                                       p_uwagi text, p_pauza_s numeric DEFAULT 0)
RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE
    v_id   bigint;
    v_cena numeric;
    v_suma numeric := 0;
BEGIN
    INSERT INTO zamowienia (klient_id, status, kwota, uwagi)
    VALUES (p_klient, 'nowe', 0, p_uwagi)
    RETURNING id INTO v_id;

    FOR i IN 1 .. array_length(p_produkty, 1) LOOP
        UPDATE produkty
           SET stan = stan - p_ilosci[i]
         WHERE id = p_produkty[i] AND stan >= p_ilosci[i]
        RETURNING cena INTO v_cena;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Brak towaru: produkt %', p_produkty[i];
        END IF;

        INSERT INTO pozycje_zamowien (zamowienie_id, produkt_id, ilosc, cena)
        VALUES (v_id, p_produkty[i], p_ilosci[i], v_cena);

        v_suma := v_suma + v_cena * p_ilosci[i];
        PERFORM pg_sleep(p_pauza_s);
    END LOOP;

    UPDATE zamowienia SET kwota = v_suma WHERE id = v_id;
    RETURN v_id;
END $$;

