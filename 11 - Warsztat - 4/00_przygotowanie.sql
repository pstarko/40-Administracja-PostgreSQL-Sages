CREATE TABLE klienci (
    id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    email      text NOT NULL UNIQUE,
    imie       text NOT NULL,
    miasto     text NOT NULL,
    utworzono  timestamptz NOT NULL DEFAULT now()
