CREATE TABLE produkty (
    id         int PRIMARY KEY,
    nazwa      text NOT NULL,
    kategoria  text NOT NULL,
    cena       numeric(10,2) NOT NULL,
    stan       int NOT NULL                -- stan magazynowy (sztuki)
