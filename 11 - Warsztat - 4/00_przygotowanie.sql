-- 5. Schemat warsztat: punkt odniesienia + automatyczna weryfikacja ------
CREATE SCHEMA warsztat;

CREATE TABLE warsztat.stan_bazowy AS
SELECT id AS produkt_id, stan, cena FROM produkty;

CREATE TABLE warsztat.parametry AS
SELECT (SELECT max(id) FROM zamowienia)                       AS max_zamowienie_id,
       (SELECT deadlocks FROM pg_stat_database
         WHERE datname = current_database())                 AS deadlocks_start;

-- Pomocnicza: czy magazyn zgadza się z zamówieniami złożonymi w trakcie warsztatu?
CREATE FUNCTION warsztat.niespojne_produkty() RETURNS bigint
LANGUAGE sql STABLE AS $$
    SELECT count(*)
    FROM warsztat.stan_bazowy b
    JOIN produkty p ON p.id = b.produkt_id
    LEFT JOIN (
        SELECT pz.produkt_id, sum(pz.ilosc) AS sprzedano
        FROM pozycje_zamowien pz
        JOIN zamowienia z ON z.id = pz.zamowienie_id
        WHERE z.id > (SELECT max_zamowienie_id FROM warsztat.parametry)
          AND z.status <> 'anulowane'
        GROUP BY pz.produkt_id
    ) s ON s.produkt_id = b.produkt_id
    WHERE p.stan <> b.stan - coalesce(s.sprzedano, 0)
$$;

CREATE FUNCTION warsztat.sprawdz(p_modul int)
RETURNS TABLE (nr int, test text, wynik text, wskazowka text)
LANGUAGE plpgsql AS $$
DECLARE
    v_base  bigint := (SELECT max_zamowienie_id FROM warsztat.parametry);
    v_ok    boolean;
    v_n     bigint;
    v_t     text;
    -- sesje czekające na blokadę (poza bieżącą)
    v_czeka bigint := (SELECT count(*) FROM pg_stat_activity
                        WHERE datname = current_database()
                          AND pid <> pg_backend_pid()
                          AND wait_event_type = 'Lock');
    -- otwarte, bezczynne transakcje (poza bieżącą)
    v_idle  bigint := (SELECT count(*) FROM pg_stat_activity
                        WHERE datname = current_database()
                          AND pid <> pg_backend_pid()
                          AND state LIKE 'idle in transaction%');
BEGIN
    IF p_modul = 0 THEN
        nr := 1; test := 'Dane: 50 000 klientów, 1 000 produktów, 200 000 zamówień';
        v_ok := (SELECT count(*) FROM klienci) = 50000
            AND (SELECT count(*) FROM produkty) = 1000
            AND (SELECT count(*) FROM zamowienia WHERE id <= v_base) = 200000;
        wynik := CASE WHEN v_ok THEN 'OK' ELSE 'BŁĄD' END;
        wskazowka := CASE WHEN v_ok THEN '' ELSE 'Uruchom ponownie 00_przygotowanie.sql' END;
        RETURN NEXT;

        nr := 2; test := 'Konsola GameBox X: dokładnie 1 sztuka na stanie';
        v_ok := (SELECT stan FROM produkty WHERE id = 1) = 1;
        wynik := CASE WHEN v_ok THEN 'OK' ELSE 'BŁĄD' END;
        wskazowka := CASE WHEN v_ok THEN '' ELSE 'Stan konsoli zmieniony – odtwórz środowisko' END;
        RETURN NEXT;

        nr := 3; test := 'Funkcje aplikacji zloz_zamowienie i zloz_zamowienie_koszyk istnieją';
        v_ok := to_regprocedure('zloz_zamowienie(bigint,int,int,text)') IS NOT NULL
            AND to_regprocedure('zloz_zamowienie_koszyk(bigint,int[],int[],text,numeric)') IS NOT NULL;
        wynik := CASE WHEN v_ok THEN 'OK' ELSE 'BŁĄD' END;
        wskazowka := '';
        RETURN NEXT;

        nr := 4; test := 'Wersja serwera: ' || current_setting('server_version');
        wynik := CASE WHEN current_setting('server_version_num')::int >= 180000 THEN 'OK' ELSE 'INFO' END;
        wskazowka := CASE WHEN wynik = 'OK' THEN ''
                          ELSE 'Warsztat przygotowano pod PG 18 – na starszej wersji część parametrów może nie istnieć' END;
        RETURN NEXT;

    ELSIF p_modul = 1 THEN
        nr := 1; test := 'Zamówienie „M1-commit” zapisane razem z pozycją (atomowość)';
        v_ok := EXISTS (SELECT 1 FROM zamowienia z JOIN pozycje_zamowien p ON p.zamowienie_id = z.id
                        WHERE z.uwagi = 'M1-commit' AND p.produkt_id = 2 AND p.ilosc = 2);
        wynik := CASE WHEN v_ok THEN 'OK' ELSE 'BŁĄD' END;
        wskazowka := CASE WHEN v_ok THEN '' ELSE 'Wykonaj zadanie 1.1 i zakończ je COMMIT' END;
        RETURN NEXT;

        nr := 2; test := 'Transakcja z błędem wycofana w całości (brak „M1-blad”, stan produktu 3 bez zmian)';
        v_ok := NOT EXISTS (SELECT 1 FROM zamowienia WHERE uwagi = 'M1-blad')
            AND (SELECT stan FROM produkty WHERE id = 3) = (SELECT stan FROM warsztat.stan_bazowy WHERE produkt_id = 3);
        wynik := CASE WHEN v_ok THEN 'OK' ELSE 'BŁĄD' END;
        wskazowka := CASE WHEN v_ok THEN '' ELSE 'Zadanie 1.2 – transakcja z błędem powinna się wycofać' END;
        RETURN NEXT;

        nr := 3; test := 'Konsola: stan 0 i dokładnie jedno aktywne zamówienie';
        v_n := (SELECT count(*) FROM zamowienia z JOIN pozycje_zamowien p ON p.zamowienie_id = z.id
                WHERE p.produkt_id = 1 AND z.id > v_base AND z.status <> 'anulowane');
        v_ok := v_n = 1 AND (SELECT stan FROM produkty WHERE id = 1) = 0;
        wynik := CASE WHEN v_ok THEN 'OK' ELSE 'BŁĄD' END;
        wskazowka := CASE WHEN v_ok THEN '' ELSE 'Aktywnych zamówień na konsolę: ' || v_n || ' – anuluj nadmiarowe (zad. 1.3)' END;
        RETURN NEXT;

        nr := 4; test := 'Ograniczenie CHECK (stan >= 0) na tabeli produkty';
        v_ok := EXISTS (SELECT 1 FROM pg_constraint
                        WHERE conrelid = 'produkty'::regclass AND contype = 'c'
                          AND pg_get_constraintdef(oid) ILIKE '%stan >= 0%');
        wynik := CASE WHEN v_ok THEN 'OK' ELSE 'BŁĄD' END;
        wskazowka := CASE WHEN v_ok THEN '' ELSE 'Dodaj ograniczenie produkty_stan_nieujemny (zad. 1.4)' END;
        RETURN NEXT;

        nr := 5; test := 'Próba kupna niedostępnej konsoli odrzucona (brak „M1-test”)';
        v_ok := NOT EXISTS (SELECT 1 FROM zamowienia WHERE uwagi = 'M1-test');
        wynik := CASE WHEN v_ok THEN 'OK' ELSE 'BŁĄD' END;
        wskazowka := '';
        RETURN NEXT;

    ELSIF p_modul = 2 THEN
        nr := 1; test := 'Widok diagnostyczny v_blokady istnieje';
        v_ok := to_regclass('v_blokady') IS NOT NULL;
        wynik := CASE WHEN v_ok THEN 'OK' ELSE 'BŁĄD' END;
        wskazowka := CASE WHEN v_ok THEN '' ELSE 'Utwórz widok z zadania 2.3' END;
        RETURN NEXT;

        nr := 2; test := 'Sesja „panel_marketingu” zakończona';
        v_ok := NOT EXISTS (SELECT 1 FROM pg_stat_activity WHERE application_name = 'panel_marketingu');
        wynik := CASE WHEN v_ok THEN 'OK' ELSE 'BŁĄD' END;
        wskazowka := CASE WHEN v_ok THEN '' ELSE 'Sesja blokująca nadal działa – zadanie 2.5' END;
        RETURN NEXT;

        nr := 3; test := 'Zamówienie „M2-www” złożone, cena produktu 12 zaktualizowana (+10 zł)';
        v_ok := EXISTS (SELECT 1 FROM zamowienia WHERE uwagi = 'M2-www')
            AND (SELECT cena FROM produkty WHERE id = 12) = (SELECT cena + 10 FROM warsztat.stan_bazowy WHERE produkt_id = 12);
        wynik := CASE WHEN v_ok THEN 'OK' ELSE 'BŁĄD' END;
        wskazowka := CASE WHEN v_ok THEN '' ELSE 'Zablokowane operacje z sesji A i B nie zakończyły się' END;
        RETURN NEXT;

        nr := 4; test := 'idle_in_transaction_session_timeout ustawiony dla roli aplikacja_sklep';
        v_t := (SELECT array_to_string(setconfig, ',') FROM pg_db_role_setting
                WHERE setrole = 'aplikacja_sklep'::regrole);
        v_ok := coalesce(v_t, '') ILIKE '%idle_in_transaction_session_timeout%';
        wynik := CASE WHEN v_ok THEN 'OK' ELSE 'BŁĄD' END;
        wskazowka := CASE WHEN v_ok THEN v_t ELSE 'ALTER ROLE aplikacja_sklep SET ... (zad. 2.6)' END;
        RETURN NEXT;

    ELSIF p_modul = 3 THEN
        nr := 1; test := 'Kolumna zamowienia.numer_faktury istnieje';
        v_ok := EXISTS (SELECT 1 FROM information_schema.columns
                        WHERE table_name = 'zamowienia' AND column_name = 'numer_faktury');
        wynik := CASE WHEN v_ok THEN 'OK' ELSE 'BŁĄD' END;
        wskazowka := CASE WHEN v_ok THEN '' ELSE 'Migracja nie została wykonana (zad. 3.5)' END;
        RETURN NEXT;

        nr := 2; test := 'lock_timeout ustawiony dla roli migrator';
        v_t := (SELECT array_to_string(setconfig, ',') FROM pg_db_role_setting
                WHERE setrole = 'migrator'::regrole);
        v_ok := coalesce(v_t, '') ILIKE '%lock_timeout%';
        wynik := CASE WHEN v_ok THEN 'OK' ELSE 'BŁĄD' END;
        wskazowka := CASE WHEN v_ok THEN v_t ELSE 'ALTER ROLE migrator SET lock_timeout = ... (zad. 3.5)' END;
        RETURN NEXT;

        nr := 3; test := 'Indeks idx_zamowienia_status istnieje i jest poprawny (indisvalid)';
        v_ok := EXISTS (SELECT 1 FROM pg_index WHERE indexrelid = to_regclass('idx_zamowienia_status') AND indisvalid);
        wynik := CASE WHEN v_ok THEN 'OK' ELSE 'BŁĄD' END;
        wskazowka := CASE WHEN v_ok THEN '' ELSE 'Utwórz indeks CONCURRENTLY; jeśli jest INVALID – usuń i utwórz ponownie (zad. 3.6)' END;
        RETURN NEXT;

        nr := 4; test := 'Sesja „raport_bi” nie trzyma otwartej transakcji';
        v_ok := NOT EXISTS (SELECT 1 FROM pg_stat_activity
                            WHERE application_name = 'raport_bi' AND xact_start IS NOT NULL);
        wynik := CASE WHEN v_ok THEN 'OK' ELSE 'BŁĄD' END;
        wskazowka := CASE WHEN v_ok THEN '' ELSE 'Zakończ transakcję w sesji C (COMMIT)' END;
        RETURN NEXT;

    ELSIF p_modul = 4 THEN
        nr := 1; test := 'Deadlock odtworzony (pg_stat_database.deadlocks wzrósł)';
        v_n := (SELECT deadlocks FROM pg_stat_database WHERE datname = current_database())
             - (SELECT deadlocks_start FROM warsztat.parametry);
        v_ok := v_n >= 1;
        wynik := CASE WHEN v_ok THEN 'OK' ELSE 'BŁĄD' END;
        wskazowka := 'Nowe deadlocki od startu warsztatu: ' || v_n;
        RETURN NEXT;

        nr := 2; test := 'log_lock_waits = on';
        v_ok := current_setting('log_lock_waits')::boolean;
        wynik := CASE WHEN v_ok THEN 'OK' ELSE 'BŁĄD' END;
        wskazowka := CASE WHEN v_ok THEN '' ELSE 'ALTER SYSTEM SET log_lock_waits = on; SELECT pg_reload_conf();' END;
        RETURN NEXT;

        nr := 3; test := 'zloz_zamowienie_koszyk blokuje produkty w stałej kolejności';
        v_ok := pg_get_functiondef('zloz_zamowienie_koszyk(bigint,int[],int[],text,numeric)'::regprocedure)
                ~* 'order\s+by\s+id\s+for\s+update';
        wynik := CASE WHEN v_ok THEN 'OK' ELSE 'BŁĄD' END;
        wskazowka := CASE WHEN v_ok THEN '' ELSE 'Wdróż poprawioną wersję funkcji (zad. 4.4)' END;
        RETURN NEXT;

        nr := 4; test := 'Zamówienia „M4-A2” i „M4-B2” złożone współbieżnie bez deadlocka';
        v_n := (SELECT count(*) FROM zamowienia z
                WHERE z.uwagi IN ('M4-A2','M4-B2')
                  AND (SELECT count(*) FROM pozycje_zamowien p WHERE p.zamowienie_id = z.id) = 2);
        v_ok := v_n = 2;
        wynik := CASE WHEN v_ok THEN 'OK' ELSE 'BŁĄD' END;
        wskazowka := CASE WHEN v_ok THEN '' ELSE 'Znaleziono kompletnych zamówień: ' || v_n || '/2 (zad. 4.5)' END;
        RETURN NEXT;
    ELSE
        RAISE EXCEPTION 'Podaj numer modułu 0–4';
    END IF;

    -- Testy wspólne dla modułów 1–4 -----------------------------------------
    IF p_modul BETWEEN 1 AND 4 THEN
        nr := 90; test := 'Spójność magazynu: stan = stan bazowy − sprzedaż z warsztatu';
        v_n := warsztat.niespojne_produkty();
        wynik := CASE WHEN v_n = 0 THEN 'OK' ELSE 'BŁĄD' END;
        wskazowka := CASE WHEN v_n = 0 THEN '' ELSE 'Niespójnych produktów: ' || v_n
                          || ' – stan zmieniony bez zamówienia (lub zamówienie bez zmiany stanu)' END;
        RETURN NEXT;

        nr := 91; test := 'Brak sesji czekających na blokadę';
        wynik := CASE WHEN v_czeka = 0 THEN 'OK' ELSE 'BŁĄD' END;
        wskazowka := CASE WHEN v_czeka = 0 THEN '' ELSE 'Czekających sesji: ' || v_czeka END;
        RETURN NEXT;

        nr := 92; test := 'Brak otwartych transakcji „idle in transaction” w innych sesjach';
        wynik := CASE WHEN v_idle = 0 THEN 'OK' ELSE 'BŁĄD' END;
        wskazowka := CASE WHEN v_idle = 0 THEN '' ELSE 'Otwartych transakcji: ' || v_idle || ' – zakończ je COMMIT/ROLLBACK' END;
        RETURN NEXT;
    END IF;
END $$;

